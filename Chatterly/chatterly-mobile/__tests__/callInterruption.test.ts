import {PermissionsAndroid, Platform} from 'react-native';
const mockNative = {addListener: jest.fn(), startMonitoring: jest.fn(), stopMonitoring: jest.fn()};
jest.mock('expo-modules-core', () => ({requireOptionalNativeModule: () => mockNative}));
import {monitorCallInterruptions} from '../src/services/callInterruption';
afterEach(() => { jest.restoreAllMocks(); jest.clearAllMocks(); });
test('subscribes before monitoring, handles denied permission and removes the listener on cleanup', async () => {
  jest.replaceProperty(Platform, 'OS', 'android');
  jest.spyOn(PermissionsAndroid, 'check').mockResolvedValue(false);
  jest.spyOn(PermissionsAndroid, 'request').mockResolvedValue('denied');
  const remove = jest.fn();
  mockNative.addListener.mockReturnValue({remove});
  const changed = jest.fn();
  const stop = monitorCallInterruptions(changed);
  await new Promise<void>(resolve => setImmediate(resolve));
  expect(mockNative.startMonitoring).toHaveBeenCalledTimes(1);
  expect(PermissionsAndroid.request).toHaveBeenCalledWith(PermissionsAndroid.PERMISSIONS.READ_PHONE_STATE);
  const listener = mockNative.addListener.mock.calls[0][1];
  listener({type: 'began'});
  listener({type: 'ended'});
  expect(changed.mock.calls).toEqual([[true], [false]]);
  stop();
  listener({type: 'began'});
  expect(changed).toHaveBeenCalledTimes(2);
  expect(remove).toHaveBeenCalled();
  expect(mockNative.stopMonitoring).toHaveBeenCalledTimes(1);
});
test('does not start monitoring after a call ends while permission is pending', async () => {
  jest.replaceProperty(Platform, 'OS', 'android');
  jest.spyOn(PermissionsAndroid, 'check').mockResolvedValue(false);
  let resolvePermission!: (result: 'granted') => void;
  jest.spyOn(PermissionsAndroid, 'request').mockImplementation(() => new Promise(resolve => { resolvePermission = resolve; }));
  mockNative.addListener.mockReturnValue({remove: jest.fn()});
  const stop = monitorCallInterruptions(jest.fn());
  await new Promise<void>(resolve => setImmediate(resolve));
  stop();
  resolvePermission('granted');
  await new Promise<void>(resolve => setImmediate(resolve));
  expect(mockNative.startMonitoring).not.toHaveBeenCalled();
});
