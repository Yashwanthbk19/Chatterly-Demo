let mockInterrupt: (active: boolean) => void;
const mockStopMonitoring = jest.fn();
jest.mock('../src/services/callInterruption', () => ({monitorCallInterruptions: jest.fn((callback: (active: boolean) => void) => { mockInterrupt = callback; return mockStopMonitoring; })}));
jest.mock('../src/services/chatRealtime', () => ({sendCallAnswerOverSocket: jest.fn(), sendCallOfferOverSocket: jest.fn(), sendIceCandidateOverSocket: jest.fn()}));
import * as audio from '../src/services/callAudio';
import * as group from '../src/services/groupCallMedia';
const rtc = require('react-native-webrtc');
afterEach(async () => { await audio.stopCallAudio(); await group.stopGroupCallMedia(); jest.clearAllMocks(); });
test.each(['caller', 'receiver'] as const)('holds a %s call on ringing and restores the original media preferences', async role => {
  await audio.startCallAudio({callId: 'interrupted', role, type: 'video'});
  const stream = rtc.mediaDevices.getUserMedia.mock.results.at(-1).value;
  const local = await stream;
  const remoteTrack = {kind: 'audio', enabled: true};
  const peer = rtc.__peerConnections.at(-1);
  peer.ontrack({streams: [new rtc.MediaStream([remoteTrack])], track: remoteTrack});
  const onHold = jest.fn();
  const unsubscribe = audio.subscribeToCallHold(onHold);
  mockInterrupt(true);
  expect(local.getTracks().every((track: any) => !track.enabled)).toBe(true);
  expect(remoteTrack.enabled).toBe(false);
  expect(onHold).toHaveBeenLastCalledWith('interrupted', true);
  await audio.setCallAudioMuted(true);
  audio.setCallVideoEnabled(false);
  mockInterrupt(true);
  mockInterrupt(false);
  expect(local.getAudioTracks()[0].enabled).toBe(false);
  expect(local.getVideoTracks()[0].enabled).toBe(false);
  expect(remoteTrack.enabled).toBe(true);
  expect(onHold).toHaveBeenLastCalledWith('interrupted', false);
  await audio.setCallAudioHeld(true);
  mockInterrupt(true);
  mockInterrupt(false);
  expect(remoteTrack.enabled).toBe(false);
  expect(onHold).toHaveBeenLastCalledWith('interrupted', true);
  await audio.stopCallAudio('interrupted');
  expect(mockStopMonitoring).toHaveBeenCalledTimes(1);
  mockInterrupt(false);
  expect(peer.close).toHaveBeenCalledTimes(1);
  unsubscribe();
});
test('also pauses group media without overwriting microphone and camera preferences', async () => {
  await group.startGroupCallMedia({groupCallId: 'group-interrupted', selfId: 'me', type: 'video', muted: false, cameraOn: true});
  const local = await rtc.mediaDevices.getUserMedia.mock.results.at(-1).value;
  mockInterrupt(true);
  expect(local.getTracks().every((track: any) => !track.enabled)).toBe(true);
  await group.setGroupCallMuted(true);
  mockInterrupt(false);
  expect(local.getAudioTracks()[0].enabled).toBe(false);
  expect(local.getVideoTracks()[0].enabled).toBe(true);
  await group.stopGroupCallMedia();
  expect(mockStopMonitoring).toHaveBeenCalledTimes(1);
});
