// Generates a small offline index for the existing picker, using Unicode CLDR.
const fs = require('fs');
const path = require('path');
const https = require('https');
const parser = require('@babel/parser');
const root = path.resolve(__dirname, '..');
const base = 'https://raw.githubusercontent.com/unicode-org/cldr-json/main/';
const files = [
  'cldr-json/cldr-annotations-full/annotations/en/annotations.json',
  'cldr-json/cldr-annotations-derived-full/annotationsDerived/en/annotations.json',
];
function download(url) {
  return new Promise((resolve, reject) => {
    https.get(url, response => {
      if (response.statusCode !== 200) { reject(new Error(`Download failed: ${response.statusCode}`)); response.resume(); return; }
      const chunks = [];
      response.on('data', chunk => chunks.push(chunk));
      response.on('end', () => resolve(Buffer.concat(chunks).toString('utf8')));
      response.on('error', reject);
    }).on('error', reject);
  });
}
async function main() {
  const source = fs.readFileSync(path.join(root, 'src/constants/emoji.ts'), 'utf8');
  const ast = parser.parse(source, {sourceType: 'module', plugins: ['typescript']});
  const definition = ast.program.body.flatMap(node => node.declarations || [])
    .find(node => node.id.name === 'EMOJI_CATEGORY_DEFINITIONS');
  const glyphs = definition.init.elements.flatMap(category =>
    category.properties.find(property => property.key.name === 'emojis').value.elements.map(node => node.value));
  const normalize = glyph => glyph.replace(/[\uFE0E\uFE0F]/g, '');
  const entries = new Map();
  for (const file of files) {
    const document = JSON.parse(await download(base + file));
    const annotations = (document.annotations || document.annotationsDerived).annotations;
    Object.entries(annotations).forEach(([glyph, entry]) => entries.set(normalize(glyph), entry));
  }
  const index = {};
  const missing = [];
  glyphs.forEach(glyph => {
    const annotation = entries.get(normalize(glyph));
    if (!annotation) { missing.push(glyph); return; }
    index[glyph] = [...new Set([...(annotation.tts || []), ...(annotation.default || [])])].join(' ');
  });
  if (missing.length) { throw new Error(`Missing CLDR names for: ${missing.join(' ')}`); }
  const output = '/** Generated by scripts/generate-emoji-search.cjs. Unicode CLDR English names and keywords.\n' +
    ' * Source: https://github.com/unicode-org/cldr-json (Unicode License v3).\n' +
    ' * Covers the existing catalogue; does not change its order or categories.\n */\n' +
    `export const EMOJI_ANNOTATIONS: Record<string, string> = ${JSON.stringify(index, null, 2)};\n`;
  fs.writeFileSync(path.join(root, 'src/constants/emojiAnnotations.ts'), output);
  const license = await download(base + 'LICENSE');
  fs.mkdirSync(path.join(root, 'licenses'), {recursive: true});
  fs.writeFileSync(path.join(root, 'licenses/Unicode-CLDR.txt'), license);
  process.stdout.write(`Indexed ${glyphs.length} emoji names and keywords.\n`);
}
main().catch(error => { process.stderr.write(`${error.message}\n`); process.exitCode = 1; });
